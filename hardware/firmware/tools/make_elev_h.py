# 0.6.1: builds include/CircuitElevation.h from the per-sector CSVs used by the sector images
# (/workspace/betaxh/hd/sectores/sector_S{1,2,3}_elevacion.csv: lap_distance_m, alt_rel_sf_m).
# Profile = GNSS altitude median of 5 passes (3876/a057 mapping + a169/b029/a7e7), 5 m bins,
# per-unit offset removed, 25 m smoothing, cross-checked vs AWS Terrarium DEM z15 (r 0.78).
import csv, numpy as np, glob
S, A = [], []
for f in sorted(glob.glob("/workspace/betaxh/hd/suave/sectores/sector_S*_elevacion.csv")):
    for r in csv.DictReader(open(f)):
        S.append(float(r["lap_distance_m"])); A.append(float(r["alt_rel_sf_m"]))
S = np.array(S); A = np.array(A); o = np.argsort(S, kind="stable"); S, A = S[o], A[o]
L = S.max(); step = 5.0; n = int(np.ceil(L / step)) + 1
grid = np.minimum(np.arange(n) * step, L)
z = np.interp(grid, S, A); dm = np.round(z * 10).astype(int)
def hyst(v, h):
    up = dn = 0.0; ref = v[0]
    for x in v[1:]:
        if x - ref >= h: up += x - ref; ref = x
        elif ref - x >= h: dn += ref - x; ref = x
    return up, dn
bnd = [0, 456.7, 913.8, L]
for th in (0.3, 0.5, 1.0):
    print(th, [tuple(round(t, 1) for t in hyst(z[(grid >= a) & (grid <= b)], th)) for a, b in zip(bnd, bnd[1:])])
base = 1742.7
rows = ",\n".join("  " + ", ".join(f"{v:5d}" for v in dm[i:i+16]) for i in range(0, n, 16))
open("/workspace/fw062/include/CircuitElevation.h", "w").write(f"""// 0.6.1-circuit: elevation profile along the embedded circuit centerline (Beta X H, 2026-10-09).
// 0.6.2-circuit.2: SMOOTHED circuit (embedded-20261009-suave, lap 1370.3 m, sectors 456.7/457.1/456.4 m).
// Same data as the sector images (betaxh_hd/suave/sectores/sector_S*_elevacion.csv): GNSS altitude median of
// 5 passes (3876 + a057 mapping, a169/b029/a7e7 laps), 5 m bins, per-unit offset removed, 25 m
// smoothing, cross-checked against AWS Terrarium DEM z15 (r = 0.78, rmse 2.9 m)  ->  label "GPS+DEM".
// NO barometer data exists for these rides. Generated by tools/make_elev_h.py.
// Sample i = altitude at lap progress i * kElevStepM (last one clamped to the lap length), int16
// decimetres relative to the S/F anchor; absolute = kElevBaseM + v / 10.
// Range {z.min():.1f} .. {z.max():.1f} m.  {n} samples = {2*n} B flash, 0 B heap.
#pragma once
#include <cstdint>
namespace riderlab {{
static constexpr int kElevN = {n};
static constexpr float kElevStepM = {step:.1f}f;
static constexpr float kElevLenM = {L:.1f}f;          // must match Circuit::lenM within 3 %
static constexpr float kElevBaseM = {base:.1f}f;       // absolute GNSS altitude of the S/F anchor (m)
static constexpr double kElevLat0 = 20.6657447, kElevLon0 = -103.4603298;  // anchor it belongs to
static constexpr const char* kElevSrc = "GPS+DEM";
static const int16_t kElevDm[kElevN] = {{
{rows}
}};
}}  // namespace riderlab
""")
print(n, z.min(), z.max(), L)
